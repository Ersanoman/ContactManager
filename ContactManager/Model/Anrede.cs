namespace ContactManager.Model
{
    /// <summary>
    /// Enumeration für die Anrede einer Person.
    /// Die Zahlenwerte entsprechen der Reihenfolge in der ComboBox im Formular.
    /// </summary>
    public enum Anrede
    {
        /// <summary>
        /// Anrede für männliche Personen
        /// </summary>
        Herr = 0,

        /// <summary>
        /// Anrede für weibliche Personen
        /// </summary>
        Frau = 1
    }
}
